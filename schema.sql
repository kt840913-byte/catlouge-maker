-- Anime Catalog API: initial schema
-- Run this in your Neon SQL Editor. Safe to run more than once.
CREATE TABLE IF NOT EXISTS anime (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  original_title TEXT,
  synopsis TEXT,
  format TEXT CHECK (format IS NULL OR format IN ('TV', 'Movie', 'OVA', 'ONA', 'Special', 'Music', 'Unknown')),
  status TEXT CHECK (status IS NULL OR status IN ('Not yet aired', 'Airing', 'Finished', 'Cancelled', 'Unknown')),
  season TEXT,
  season_year INTEGER CHECK (season_year IS NULL OR season_year BETWEEN 1900 AND 2200),
  episodes INTEGER CHECK (episodes IS NULL OR episodes >= 0),
  release_date DATE,
  slug TEXT UNIQUE,
  cover_image_url TEXT,
  banner_image_url TEXT,
  source_material TEXT,
  age_rating TEXT,
  average_score NUMERIC(4,2) CHECK (average_score IS NULL OR average_score BETWEEN 0 AND 100),
  popularity INTEGER CHECK (popularity IS NULL OR popularity >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS genres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS studios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  website_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS anime_studios (
  anime_id BIGINT NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
  studio_id BIGINT NOT NULL REFERENCES studios(id) ON DELETE CASCADE,
  PRIMARY KEY (anime_id, studio_id)
);

CREATE TABLE IF NOT EXISTS anime_genres (
  anime_id BIGINT NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
  genre_id BIGINT NOT NULL REFERENCES genres(id) ON DELETE CASCADE,
  PRIMARY KEY (anime_id, genre_id)
);

CREATE INDEX IF NOT EXISTS idx_anime_title ON anime USING LOWER (title);
CREATE INDEX IF NOT EXISTS idx_anime_year ON anime (season_year);
CREATE INDEX IF NOT EXISTS idx_anime_status ON anime (status);

